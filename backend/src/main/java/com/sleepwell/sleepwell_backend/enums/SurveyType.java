package com.sleepwell.sleepwell_backend.enums;

/**
 * 수면 설문 유형
 */
public enum SurveyType {
    ISI,        // Insomnia Severity Index (불면증 심각도 지수)
    PSQI,       // Pittsburgh Sleep Quality Index (피츠버그 수면의 질 지수)
    ESS,        // Epworth Sleepiness Scale (엡워스 졸림 척도)
    BDI_II      // Beck Depression Inventory-II (벡 우울 척도 II)
}
